"""Builds supabase/setup.sql: the whole database, in one file, for a NEW (empty) Supabase project.
Run it again after adding a new update file:   python tools/build-setup.py
Add the new file's name at the END of ORDER below."""
import os

ORDER = [
    'schema.sql', 'admin-update.sql', 'hardening-update.sql', 'approvals-update.sql', 'offline-sync-update.sql',
    'statuses-update.sql', 'money-devices-update.sql', 'deadlines-update.sql', 'security-update.sql',
    'calendar-update.sql', 'error-log-update.sql',
]
here = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'supabase')
out = ["""-- ============================================================================================================
-- DIRECTOR KOLLO: COMPLETE DATABASE SETUP FOR A NEW, EMPTY SUPABASE PROJECT
-- Run this ONE file once, in Supabase > SQL Editor. Then run rls-checks.sql to prove the rules hold.
-- It is the old files run in order, so a project that already ran them does NOT need this file.
-- Generated by tools/build-setup.py. Do not edit by hand: edit the update files and rebuild.
-- ============================================================================================================
"""]
for name in ORDER:
    body = open(os.path.join(here, name), encoding='utf-8').read().rstrip() + '\n'
    out.append('\n-- ' + '=' * 108 + '\n-- PART: ' + name + '\n-- ' + '=' * 108 + '\n' + body)
open(os.path.join(here, 'setup.sql'), 'w', encoding='utf-8').write(''.join(out))
print('wrote supabase/setup.sql from', len(ORDER), 'files')
